import { defineConfig } from 'tsup'

/**
 * The **plugin** build: one self-contained file, committed, that
 * `plugins/claude-code/` launches.
 *
 * `tsup.config.ts` beside this one produces `dist/index.js` for npm: it leaves
 * every dependency as a bare import and relies on `node_modules` being there.
 * An installed plugin has no `node_modules`: the host copies the plugin
 * directory and runs `node ${CLAUDE_PLUGIN_ROOT}/server/kleora-mcp.mjs`, so
 * anything the file does not carry itself is a crash on the first tool call.
 * Hence `noExternal` matching everything, `@kleora-io/core` included.
 *
 * `@napi-rs/keyring` stays external for the reason `tsup.config.ts` gives
 * (a different native binding per platform, resolved at its own
 * require-time) and for a second one: it is optional by design.
 * `@kleora-io/core` imports it dynamically inside a `try`, so the bundled
 * server runs with no keychain module present, on the `0600` file store, and
 * picks the keychain up when `plugins/claude-code/package.json`'s
 * `optionalDependencies` entry has been installed.
 *
 * The output is checked in (`plugins/claude-code/server/kleora-mcp.mjs`) and
 * regenerated by `pnpm plugin-server`; `pnpm check:plugin-server` rebuilds it
 * into a temporary directory and diffs, so a change to `src/` that never
 * reached the plugin fails CI. Not minified: a generated artefact still lands
 * in a diff somebody reads.
 *
 * `metafile` is on because the bundle is not the only output that has to be
 * checked in. `scripts/generate-plugin-notices.mjs` reads it to write the
 * `THIRD-PARTY-NOTICES` that ships beside the bundle: a bundled dependency is
 * a *copy* of it, and MIT, BSD and ISC all require their notice to travel with
 * copies. The metafile is the only honest source for that list, since a
 * bundler inlines transitive dependencies too, and taking it from the same
 * build means the notices cannot describe a different tree from the bundle
 * they sit next to.
 */
export default defineConfig({
  entry: { 'kleora-mcp': 'src/index.ts' },
  outDir: process.env.KLEORA_PLUGIN_SERVER_OUT ?? 'plugin-server',
  format: ['esm'],
  outExtension: () => ({ js: '.mjs' }),
  target: 'node20',
  platform: 'node',
  // `noExternal` wins over `external` in tsup, so the keyring is excluded
  // here rather than named there: everything but that one module is inlined.
  noExternal: [/^(?!@napi-rs\/keyring$).*$/],
  external: ['@napi-rs/keyring'],
  treeshake: true,
  minify: false,
  sourcemap: false,
  dts: false,
  metafile: true,
  // **Not** `clean`, unlike `tsup.config.ts`. `build-plugin-server.sh` always
  // builds into a fresh temporary directory and copies the two artefacts into
  // the plugin, so there is nothing here to clean; but a developer running
  // `pnpm build:plugin` by hand gets `plugin-server/` in this package, and a
  // clean there is a surprise nobody asked for.
  clean: false,
  banner: {
    js: [
      '#!/usr/bin/env node',
      '// GENERATED FILE — do not edit.',
      '// Written by `pnpm plugin-server` from packages/mcp/src; checked by',
      '// `pnpm check:plugin-server`. Edit the TypeScript source instead.',
    ].join('\n'),
  },
})
